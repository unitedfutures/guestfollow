const DICT: Record<GuestLang, Dict> = {
  ja, en, 'zh-CN': zhCN, 'zh-TW': zhTW, ko, th, vi, id, fr, de, es, it, pt, ru, hi,
}

export function guestT(lang: GuestLang, key: string, vars?: Record<string, string | number>): string {
  let s = DICT[lang]?.[key] ?? DICT.ja[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v))
    }
  }
  return s
}
